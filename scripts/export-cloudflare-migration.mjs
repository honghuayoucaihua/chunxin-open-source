import fs from 'node:fs/promises';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { SCHEMA_SQL } from '../cloudflare/pages-functions/data.js';
import { prepareCommunityPayloadForStorage } from '../src/community/communityPayloadShared.js';

const [, , sqlitePathArg, uploadsDirArg, outputDirArg] = process.argv;

if (!sqlitePathArg || !uploadsDirArg || !outputDirArg) {
  console.error('Usage: node scripts/export-cloudflare-migration.mjs <sqlite-db> <uploads-dir> <output-dir>');
  process.exit(1);
}

const sqlitePath = path.resolve(sqlitePathArg);
const uploadsDir = path.resolve(uploadsDirArg);
const outputDir = path.resolve(outputDirArg);

const db = new DatabaseSync(sqlitePath, { readonly: true });

const ensureDir = async (dir) => {
  await fs.mkdir(dir, { recursive: true });
};

const sqlValue = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  return `'${String(value).replace(/'/g, "''")}'`;
};

const getRows = (sql) => db.prepare(sql).all();

const parseJsonArray = (value) => {
  if (typeof value !== 'string' || !value.trim()) return [];
  try {
    const parsed = JSON.parse(value);
    return Array.isArray(parsed) ? parsed.map((item) => String(item || '').trim()).filter(Boolean) : [];
  } catch {
    return [];
  }
};

const quoteIdentifier = (value) => `"${String(value).replace(/"/g, '""')}"`;

const buildInsert = (table, columns, row) => (
  `INSERT INTO ${table} (${columns.map((column) => quoteIdentifier(column)).join(', ')}) VALUES (${columns.map((column) => sqlValue(row[column])).join(', ')});`
);

const main = async () => {
  await ensureDir(outputDir);

  const appSettings = getRows('SELECT key, value, updated_at FROM app_settings');
  const passphrases = getRows('SELECT id, phrase, "limit", valid_days, is_active, created_at, updated_at FROM passphrases ORDER BY created_at ASC');
  const teamNotices = getRows('SELECT id, title, content, type, created_at FROM team_notices ORDER BY created_at ASC');
  const donors = getRows('SELECT id, name, amount, message, date, created_at FROM donors ORDER BY created_at ASC');
  const apkVersions = getRows('SELECT id, version, versionCode, apkUrl, apkSize, updateLog, forceUpdate, minVersion, created_at FROM apk_versions ORDER BY versionCode ASC, created_at ASC');
  const skippedDailyUsageCount = getRows("SELECT COUNT(*) AS total FROM user_usage WHERE date IS NOT NULL AND TRIM(date) != '' AND count > 0")[0]?.total || 0;
  const communityShares = getRows(`
    SELECT
      id, client_id, type, name, description, avatar, cover_image, author_name, author_password_hash,
      is_anonymous, is_encrypted, payload, like_count, download_count, report_count, created_at,
      liked_by, reported_by
    FROM community_shares
    ORDER BY created_at ASC
  `);

  const sqlLines = [
    '-- Generated by scripts/export-cloudflare-migration.mjs',
    'PRAGMA defer_foreign_keys = on;',
    SCHEMA_SQL.trim(),
    'DELETE FROM community_share_reports;',
    'DELETE FROM community_share_likes;',
    'DELETE FROM community_shares;',
    'DELETE FROM apk_versions;',
    'DELETE FROM certificates;',
    'DELETE FROM donors;',
    'DELETE FROM team_notices;',
    'DELETE FROM daily_usage;',
    'DELETE FROM passphrases;',
    'DELETE FROM app_settings;'
  ];

  const manifestLines = [];
  const uploadedSourceSet = new Set();
  let trimmedCommunityShareCount = 0;

  for (const row of appSettings) {
    sqlLines.push(buildInsert('app_settings', ['key', 'value', 'updated_at'], row));
  }

  for (const row of passphrases) {
    sqlLines.push(buildInsert('passphrases', ['id', 'phrase', 'limit', 'valid_days', 'is_active', 'created_at', 'updated_at'], row));
  }

  for (const row of teamNotices) {
    sqlLines.push(buildInsert('team_notices', ['id', 'title', 'content', 'type', 'created_at'], row));
  }

  for (const row of donors) {
    sqlLines.push(buildInsert('donors', ['id', 'name', 'amount', 'message', 'date', 'created_at'], row));
  }

  for (const row of apkVersions) {
    sqlLines.push(buildInsert('apk_versions', ['id', 'version', 'versionCode', 'apkUrl', 'apkSize', 'updateLog', 'forceUpdate', 'minVersion', 'created_at', 'updated_at'], {
      ...row,
      updated_at: row.created_at
    }));
  }

  for (const row of communityShares) {
    let coverImage = typeof row.cover_image === 'string' ? row.cover_image.trim() : '';
    let coverObjectKey = '';
    const originalPayloadString = typeof row.payload === 'string' ? row.payload : JSON.stringify(row.payload ?? {});
    const preparedPayload = prepareCommunityPayloadForStorage(
      row.type,
      originalPayloadString,
      Number(row.is_encrypted || 0) === 1
    );
    if (preparedPayload.payloadString !== originalPayloadString) {
      trimmedCommunityShareCount += 1;
    }

    if (coverImage.startsWith('/uploads/')) {
      const filename = path.basename(coverImage);
      const sourcePath = path.join(uploadsDir, filename);
      coverObjectKey = `community/covers/${filename}`;
      coverImage = `/api/community/assets/${encodeURIComponent(coverObjectKey)}`;
      if (!uploadedSourceSet.has(sourcePath)) {
        manifestLines.push(`${sourcePath}\t${coverObjectKey}`);
        uploadedSourceSet.add(sourcePath);
      }
    }

    sqlLines.push(buildInsert('community_shares', [
      'id',
      'client_id',
      'type',
      'name',
      'description',
      'avatar',
      'cover_image',
      'cover_object_key',
      'author_name',
      'author_password_hash',
      'is_anonymous',
      'is_encrypted',
      'payload',
      'like_count',
      'download_count',
      'report_count',
      'status',
      'created_at',
      'updated_at'
    ], {
      id: row.id,
      client_id: row.client_id,
      type: row.type,
      name: row.name,
      description: row.description ?? '',
      avatar: row.avatar ?? '',
      cover_image: coverImage,
      cover_object_key: coverObjectKey,
      author_name: row.author_name ?? '',
      author_password_hash: row.author_password_hash ?? '',
      is_anonymous: row.is_anonymous ?? 0,
      is_encrypted: row.is_encrypted ?? 0,
      payload: preparedPayload.payloadString,
      like_count: row.like_count ?? 0,
      download_count: row.download_count ?? 0,
      report_count: row.report_count ?? 0,
      status: 'active',
      created_at: row.created_at,
      updated_at: row.created_at
    }));

    for (const clientId of new Set(parseJsonArray(row.liked_by))) {
      sqlLines.push(buildInsert('community_share_likes', ['post_id', 'client_id', 'created_at'], {
        post_id: row.id,
        client_id: clientId,
        created_at: row.created_at
      }));
    }

    for (const clientId of new Set(parseJsonArray(row.reported_by))) {
      sqlLines.push(buildInsert('community_share_reports', ['post_id', 'client_id', 'created_at'], {
        post_id: row.id,
        client_id: clientId,
        created_at: row.created_at
      }));
    }
  }

  const sqlPath = path.join(outputDir, 'migration.sql');
  const manifestPath = path.join(outputDir, 'r2-manifest.tsv');
  const summaryPath = path.join(outputDir, 'summary.json');

  await fs.writeFile(sqlPath, `${sqlLines.join('\n')}\n`, 'utf8');
  await fs.writeFile(manifestPath, `${manifestLines.join('\n')}\n`, 'utf8');
  await fs.writeFile(summaryPath, JSON.stringify({
    appSettings: appSettings.length,
    passphrases: passphrases.length,
    teamNotices: teamNotices.length,
    donors: donors.length,
    apkVersions: apkVersions.length,
    skippedDailyUsageRows: skippedDailyUsageCount,
    communityShares: communityShares.length,
    trimmedCommunityShares: trimmedCommunityShareCount,
    r2Uploads: manifestLines.length
  }, null, 2), 'utf8');

  console.log(JSON.stringify({
    sqlPath,
    manifestPath,
    summaryPath,
    counts: {
      appSettings: appSettings.length,
      passphrases: passphrases.length,
      teamNotices: teamNotices.length,
      donors: donors.length,
      apkVersions: apkVersions.length,
      skippedDailyUsageRows: skippedDailyUsageCount,
      communityShares: communityShares.length,
      trimmedCommunityShares: trimmedCommunityShareCount,
      r2Uploads: manifestLines.length
    }
  }, null, 2));
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
